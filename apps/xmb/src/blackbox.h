#ifndef XMB_BLACKBOX_H
#define XMB_BLACKBOX_H

/* «Чёрный ящик» (XMB-0024, XMB-0061): короткая строка о шаге, после которого бывает падение ядра (тракт звука, сон,
 * внешние команды, кнопки), — сразу на карту с O_SYNC: журнал ядра при перезагрузке теряется, обычный журнал XMB не
 * успевает дойти до карты. Последняя строка — последнее, что XMB успел сделать. Файл — hiby_dev/bb.log (прошлая
 * загрузка — bb.log.prev, его переносит run_xmb.sh), до 256 КБ; на ПК — ничего. */
void bb(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
void bb_set(int on);   /* настройка «Журнал диагностики»: 0 — ничего не пишется */

#endif
